function shuffled<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function getQuestionsForSubsection(subsectionId: string): QuizQuestion[] {
  const questions = questionBank[subsectionId] || questionBank["default"];
  return shuffled(questions).map((q) => {
    const shuffledOptions = shuffled(
      q.options.map((text, i) => ({
        text,
        graph: q.optionGraphs?.[i],
        wasCorrect: i === q.correctAnswer,
      }))
    );
    return {
      ...q,
      options: shuffledOptions.map((o) => o.text),
      optionGraphs: q.optionGraphs
        ? shuffledOptions.map((o) => o.graph!)
        : undefined,
      correctAnswer: shuffledOptions.findIndex((o) => o.wasCorrect),
    };
  });
}
